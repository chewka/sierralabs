/* The Lab Sims — science.js
   Simulation models and chart rendering.

   EVERY number produced here is generated by this file's own toy model.
   Nothing in here is measured data and nothing should be read as a published
   result. Trend DIRECTIONS follow the general methodology the workflows are
   modelled on; magnitudes, noise and probabilities are gameplay values. */
(function () {
  const LS = window.LS;
  const Sci = (LS.Sci = {});

  /* =========================================================
     MODELS
     ========================================================= */

  /* --- Experiment A: recovery of encapsulated cells after lyophilisation --- */
  Sci.PROTECTANTS = [
    { id: 'water', label: 'Water control', base: 0.11, sd: 0.035 },
    { id: 'treh', label: 'Trehalose', base: 0.57, sd: 0.07 },
    { id: 'pro', label: 'Proline', base: 0.40, sd: 0.07 },
    { id: 'trehgly', label: 'Trehalose + glycerol', base: 0.71, sd: 0.06 },
    { id: 'progly', label: 'Proline + glycerol', base: 0.54, sd: 0.07 },
  ];
  Sci.STORAGE = [
    { id: 'm1', label: '1 month', months: 1, decay: 1.0 },
    { id: 'm3', label: '3 months', months: 3, decay: 0.93 },
    { id: 'm6', label: '6 months', months: 6, decay: 0.84 },
  ];

  Sci.recovery = function (protId, storId, flags, rng) {
    const p = Sci.PROTECTANTS.find((x) => x.id === protId) || Sci.PROTECTANTS[0];
    const s = Sci.STORAGE.find((x) => x.id === storId) || Sci.STORAGE[0];
    let r = p.base * s.decay * rng.norm(1, p.sd / Math.max(0.2, p.base) * 0.22 + 0.04);
    if (flags.contaminated) r *= 0.55;
    if (flags.tempDrift) r *= 0.88;
    if (flags.identityUncertain) r *= 1.0; // identity does not change the number, only its trustworthiness
    return LS.clamp(r, 0.005, 1.15);
  };

  /* --- Experiment B: protein production across reuse rounds --- */
  Sci.PROTEINS = [
    { id: 'seap', label: 'SEAP', unit: 'RLU ×10⁵', scale: 7.4, assay: 'Chemiluminescence', station: 'reader' },
    { id: 'amylase', label: 'α-amylase', unit: 'U/mL', scale: 2.9, assay: 'Starch activity assay', station: 'reader' },
    { id: 'her2', label: 'Anti-HER2', unit: 'mg/L', scale: 1.35, assay: 'Western blot detection', station: 'bench' },
  ];
  Sci.strainScreen = function (rng) {
    const names = ['YS-01', 'YS-02', 'YS-07', 'YS-11', 'YS-14', 'YS-19'];
    return names.map((n) => ({ name: n, score: LS.clamp(rng.norm(1, 0.35), 0.25, 2.1) }));
  };
  Sci.proteinRound = function (protId, round, strainQ, flags, rng) {
    const p = Sci.PROTEINS.find((x) => x.id === protId) || Sci.PROTEINS[0];
    const reuse = Math.pow(0.9, round - 1);
    let v = p.scale * strainQ * reuse * rng.norm(1, 0.09);
    if (flags.contaminated) v *= 0.4;
    if (flags.tempDrift) v *= 0.9;
    if (flags.rehydrated) v *= 0.82;
    return { value: Math.max(0.01, v), unit: p.unit, label: p.label };
  };

  /* --- Experiment C: three-module consortium flux --- */
  /* Simple sequential-capacity model: each module converts what the one
     upstream hands it, up to its own capacity. Intermediates pile up when a
     downstream module is under-represented. */
  Sci.consortium = function (ratio, encapsulated, flags, rng) {
    const tot = ratio[0] + ratio[1] + ratio[2];
    const f = ratio.map((r) => r / tot);
    const CAP = [86, 70, 44]; // arbitrary gameplay capacities, mg/L-equivalents
    const boost = encapsulated ? 1.12 : 1.0;
    const noise = () => rng.norm(1, 0.07);
    const coumaric = CAP[0] * f[0] * 3 * noise() * boost;
    const ferulicCap = CAP[1] * f[1] * 3 * noise() * boost;
    const ferulic = Math.min(coumaric, ferulicCap);
    const eugenolCap = CAP[2] * f[2] * 3 * noise() * boost;
    const eugenol = Math.min(ferulic, eugenolCap);
    let out = {
      coumaric: Math.max(0, coumaric - ferulic),
      ferulic: Math.max(0, ferulic - eugenol),
      eugenol: Math.max(0, eugenol),
      flux: eugenol / Math.max(1, coumaric),
    };
    if (flags.contaminated) { out.eugenol *= 0.45; out.coumaric *= 1.2; }
    if (flags.tempDrift) { out.eugenol *= 0.9; }
    return out;
  };

  /* --- Experiment D: biosensor kinetics --- */
  Sci.biosensor = function (stimulus, fed, flags, rng, points) {
    /* stimulus 0..1; returns kinetic series sampled every 15 simulated minutes */
    const Fmax = 1400 * (0.35 + 0.65 * (stimulus / (0.28 + stimulus)));
    const lag = fed ? 52 : 38;
    const tau = fed ? 86 : 66;
    const odMax = fed ? 1.15 : 0.82;
    const fl = [], od = [];
    for (let i = 0; i < points; i++) {
      const t = i * 15;
      let f = t < lag ? 0 : Fmax * (1 - Math.exp(-(t - lag) / tau));
      f *= rng.norm(1, 0.045);
      if (flags.contaminated) f *= 0.6;
      let o = odMax / (1 + Math.exp(-(t - 120) / 48)) * rng.norm(1, 0.03);
      fl.push([t / 60, Math.max(0, f)]);
      od.push([t / 60, Math.max(0.02, o)]);
    }
    return { fl, od, Fmax };
  };
  Sci.viability = function (treated, flags, rng) {
    const base = treated ? rng.norm(88, 4) : rng.norm(95, 2.5);
    return LS.clamp(base * (flags.contaminated ? 0.8 : 1), 5, 100);
  };

  /* --- generic growth curve for incubations --- */
  Sci.growth = function (hours, tempOK, rng, n) {
    const K = tempOK ? 1.9 : 1.35, r = tempOK ? 0.17 : 0.12;
    const pts = [];
    for (let i = 0; i <= n; i++) {
      const t = (hours * i) / n;
      pts.push([t, LS.clamp((K / (1 + ((K - 0.05) / 0.05) * Math.exp(-r * t))) * rng.norm(1, 0.02), 0, 3)]);
    }
    return pts;
  };

  /* --- chromatogram peak sets --- */
  Sci.chromPeaks = function (which, data, rng) {
    if (which === 'C') {
      return [
        { rt: 3.4, h: Math.max(2, data.coumaric * 0.9), w: 0.16, name: 'p-coumaric' },
        { rt: 4.9, h: Math.max(2, data.ferulic * 1.0), w: 0.17, name: 'ferulic' },
        { rt: 7.8, h: Math.max(2, data.eugenol * 1.6), w: 0.2, name: 'eugenol' },
        { rt: 1.6, h: rng.range(6, 14), w: 0.13, name: 'medium' },
      ];
    }
    return [
      { rt: 2.1, h: rng.range(10, 18), w: 0.13, name: 'medium' },
      { rt: 5.2, h: Math.max(3, data.tryptamine || rng.range(14, 40)), w: 0.18, name: 'tryptamine' },
      { rt: 8.6, h: Math.max(2, data.carboline || rng.range(5, 22)), w: 0.2, name: 'β-carboline' },
    ];
  };

  /* =========================================================
     CHARTS  (crisp DOM canvas, not pixel art)
     ========================================================= */
  const CH = {
    bg: 'transparent', grid: '#232b38', axis: '#3c465a', tick: '#7f8b9e',
    ink: '#c3ccd9', series: ['#2fb8a8', '#f0a93b', '#8a6bd6', '#e06b8b', '#4a8fd4'],
  };
  Sci.CH = CH;

  function prep(cv) {
    const dpr = window.devicePixelRatio || 1;
    const r = cv.getBoundingClientRect();
    const w = Math.max(80, r.width), h = Math.max(60, r.height);
    if (cv.width !== Math.round(w * dpr) || cv.height !== Math.round(h * dpr)) {
      cv.width = Math.round(w * dpr); cv.height = Math.round(h * dpr);
    }
    const c = cv.getContext('2d');
    c.setTransform(dpr, 0, 0, dpr, 0, 0);
    c.clearRect(0, 0, w, h);
    c.font = '9px "IBM Plex Mono", ui-monospace, monospace';
    return { c, w, h };
  }
  Sci.prep = prep;

  function frame(c, w, h, cfg, xmin, xmax, ymin, ymax) {
    const L = 34, R = 8, Tp = 16, B = 20;
    const pw = w - L - R, ph = h - Tp - B;
    c.strokeStyle = CH.grid; c.lineWidth = 1;
    for (let i = 0; i <= 4; i++) {
      const y = Tp + (ph * i) / 4 + 0.5;
      c.beginPath(); c.moveTo(L, y); c.lineTo(L + pw, y); c.stroke();
      const v = ymax - ((ymax - ymin) * i) / 4;
      c.fillStyle = CH.tick; c.textAlign = 'right'; c.textBaseline = 'middle';
      c.fillText(LS.sci(v, 1), L - 4, y);
    }
    for (let i = 0; i <= 4; i++) {
      const x = L + (pw * i) / 4 + 0.5;
      c.strokeStyle = CH.grid; c.beginPath(); c.moveTo(x, Tp); c.lineTo(x, Tp + ph); c.stroke();
      const v = xmin + ((xmax - xmin) * i) / 4;
      c.fillStyle = CH.tick; c.textAlign = 'center'; c.textBaseline = 'top';
      c.fillText(LS.round1(v), x, Tp + ph + 4);
    }
    c.strokeStyle = CH.axis;
    c.beginPath(); c.moveTo(L + 0.5, Tp); c.lineTo(L + 0.5, Tp + ph + 0.5); c.lineTo(L + pw, Tp + ph + 0.5); c.stroke();
    if (cfg.title) { c.fillStyle = CH.ink; c.textAlign = 'left'; c.textBaseline = 'top'; c.fillText(cfg.title, L, 2); }
    if (cfg.xlab) { c.fillStyle = CH.tick; c.textAlign = 'right'; c.textBaseline = 'bottom'; c.fillText(cfg.xlab, w - R, h - 1); }
    return { L, R, Tp, B, pw, ph };
  }

  Sci.lineChart = function (cv, cfg) {
    const { c, w, h } = prep(cv);
    const series = (cfg.series || []).filter((s) => s.pts && s.pts.length);
    if (!series.length) { c.fillStyle = CH.tick; c.textAlign = 'center'; c.fillText(cfg.empty || 'no data yet', w / 2, h / 2); return; }
    let xmin = Infinity, xmax = -Infinity, ymin = 0, ymax = -Infinity;
    series.forEach((s) => s.pts.forEach(([x, y]) => { xmin = Math.min(xmin, x); xmax = Math.max(xmax, x); ymax = Math.max(ymax, y); }));
    if (cfg.xmax !== undefined) xmax = Math.max(xmax, cfg.xmax);
    if (cfg.ymax !== undefined) ymax = Math.max(ymax, cfg.ymax);
    if (xmax - xmin < 1e-6) xmax = xmin + 1;
    ymax = ymax * 1.12 || 1;
    const g = frame(c, w, h, cfg, xmin, xmax, ymin, ymax);
    const X = (v) => g.L + ((v - xmin) / (xmax - xmin)) * g.pw;
    const Y = (v) => g.Tp + g.ph - ((v - ymin) / (ymax - ymin)) * g.ph;
    series.forEach((s, i) => {
      const col = s.color || CH.series[i % CH.series.length];
      c.strokeStyle = col; c.lineWidth = 1.6; c.lineJoin = 'round';
      c.beginPath();
      s.pts.forEach(([x, y], k) => (k ? c.lineTo(X(x), Y(y)) : c.moveTo(X(x), Y(y))));
      c.stroke();
      if (s.dots !== false && s.pts.length < 40) {
        c.fillStyle = col;
        s.pts.forEach(([x, y]) => c.fillRect(X(x) - 1.5, Y(y) - 1.5, 3, 3));
      }
    });
    // legend
    let lx = g.L + 2;
    c.textAlign = 'left'; c.textBaseline = 'top';
    series.forEach((s, i) => {
      if (!s.name) return;
      const col = s.color || CH.series[i % CH.series.length];
      c.fillStyle = col; c.fillRect(lx, 4, 6, 6);
      c.fillStyle = CH.ink; c.fillText(s.name, lx + 9, 3);
      lx += 14 + c.measureText(s.name).width;
    });
  };

  Sci.barChart = function (cv, cfg) {
    const { c, w, h } = prep(cv);
    const bars = cfg.bars || [];
    if (!bars.length) { c.fillStyle = CH.tick; c.textAlign = 'center'; c.fillText(cfg.empty || 'no data yet', w / 2, h / 2); return; }
    const ymax = Math.max(...bars.map((b) => b.v)) * 1.18 || 1;
    const L = 34, R = 8, Tp = 16, B = 22, pw = w - L - R, ph = h - Tp - B;
    c.strokeStyle = CH.grid;
    for (let i = 0; i <= 4; i++) {
      const y = Tp + (ph * i) / 4 + 0.5;
      c.beginPath(); c.moveTo(L, y); c.lineTo(L + pw, y); c.stroke();
      c.fillStyle = CH.tick; c.textAlign = 'right'; c.textBaseline = 'middle';
      c.fillText(LS.sci(ymax - (ymax * i) / 4, 1), L - 4, y);
    }
    c.strokeStyle = CH.axis; c.beginPath(); c.moveTo(L + 0.5, Tp); c.lineTo(L + 0.5, Tp + ph + 0.5); c.lineTo(L + pw, Tp + ph + 0.5); c.stroke();
    if (cfg.title) { c.fillStyle = CH.ink; c.textAlign = 'left'; c.textBaseline = 'top'; c.fillText(cfg.title, L, 2); }
    const bw = pw / bars.length;
    bars.forEach((b, i) => {
      const bh = (b.v / ymax) * ph;
      const x = L + i * bw + bw * 0.18, ww = bw * 0.64;
      c.fillStyle = b.color || CH.series[i % CH.series.length];
      c.fillRect(x, Tp + ph - bh, ww, bh);
      c.fillStyle = CH.tick; c.textAlign = 'center'; c.textBaseline = 'top';
      c.fillText(b.label, x + ww / 2, Tp + ph + 4);
    });
  };

  Sci.chromatogram = function (cv, cfg) {
    const { c, w, h } = prep(cv);
    const peaks = cfg.peaks || [];
    const run = cfg.progress === undefined ? 1 : LS.clamp(cfg.progress, 0, 1);
    const tmax = cfg.tmax || 10;
    const ymax = Math.max(10, ...peaks.map((p) => p.h)) * 1.25;
    const g = frame(c, w, h, { title: cfg.title || 'Chromatogram', xlab: 'min' }, 0, tmax, 0, ymax);
    const X = (v) => g.L + (v / tmax) * g.pw;
    const Y = (v) => g.Tp + g.ph - (v / ymax) * g.ph;
    const N = 260, cut = Math.floor(N * run);
    c.strokeStyle = cfg.color || CH.series[0]; c.lineWidth = 1.4;
    c.beginPath();
    for (let i = 0; i <= cut; i++) {
      const t = (tmax * i) / N;
      let v = 2 + Math.sin(t * 7.3) * 0.6 + Math.sin(t * 23.1) * 0.35;
      peaks.forEach((p) => { v += p.h * Math.exp(-Math.pow(t - p.rt, 2) / (2 * p.w * p.w)); });
      i ? c.lineTo(X(t), Y(v)) : c.moveTo(X(t), Y(v));
    }
    c.stroke();
    if (run >= 0.999) {
      c.fillStyle = CH.ink; c.textAlign = 'center'; c.textBaseline = 'bottom';
      peaks.forEach((p) => { if (p.h > ymax * 0.1) c.fillText(p.name, X(p.rt), Y(p.h) - 3); });
    } else {
      const t = tmax * run;
      c.strokeStyle = '#f0a93b'; c.setLineDash([2, 3]);
      c.beginPath(); c.moveTo(X(t), g.Tp); c.lineTo(X(t), g.Tp + g.ph); c.stroke(); c.setLineDash([]);
    }
  };
})();
